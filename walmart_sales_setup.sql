DROP DATABASE IF EXISTS walmart_sales;
CREATE DATABASE walmart_sales;
USE walmart_sales;

-- --------------------------------------------------------------------------
-- 1. DIMENSION TABLES
-- --------------------------------------------------------------------------
CREATE TABLE branches (
    branch_id    INT PRIMARY KEY,
    branch_code  CHAR(1)      NOT NULL,
    branch_name  VARCHAR(50)  NOT NULL,
    city         VARCHAR(50)  NOT NULL,
    region       VARCHAR(20)  NOT NULL
);

CREATE TABLE products (
    product_id    INT PRIMARY KEY,
    product_line  VARCHAR(60)    NOT NULL,
    unit_price    DECIMAL(10,2)  NOT NULL
);

CREATE TABLE customers (
    customer_id    INT PRIMARY KEY,
    customer_type  ENUM('Member','Normal')  NOT NULL,
    gender         ENUM('Male','Female')    NOT NULL,
    city           VARCHAR(50)              NOT NULL
);

-- --------------------------------------------------------------------------
-- 2. FACT TABLE
-- --------------------------------------------------------------------------
CREATE TABLE sales (
    sale_id         INT PRIMARY KEY,
    invoice_no      VARCHAR(20)   NOT NULL,
    branch_id       INT           NOT NULL,
    customer_id     INT           NOT NULL,
    product_id      INT           NOT NULL,
    quantity        INT           NOT NULL,
    sale_date       DATE          NOT NULL,
    sale_time       TIME          NOT NULL,
    payment_method  ENUM('Cash','Credit card','Ewallet') NOT NULL,
    rating          DECIMAL(3,1)  NOT NULL,
    CONSTRAINT fk_sales_branch   FOREIGN KEY (branch_id)   REFERENCES branches(branch_id),
    CONSTRAINT fk_sales_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT fk_sales_product  FOREIGN KEY (product_id)  REFERENCES products(product_id)
);

-- Helpful indexes for the analysis queries
CREATE INDEX idx_sales_date    ON sales(sale_date);
CREATE INDEX idx_sales_branch  ON sales(branch_id);
CREATE INDEX idx_sales_product ON sales(product_id);

